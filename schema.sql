-- Runtime data only. Venue details stay in public/data/venues.json.
CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL,
  email text NOT NULL,
  "passwordHash" text NOT NULL,
  role text NOT NULL CHECK (role IN ('student', 'faculty', 'admin')),
  "createdAt" timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users (lower(email));

CREATE TABLE IF NOT EXISTS bookings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "venueId" integer NOT NULL,
  date date NOT NULL,
  "startTime" time NOT NULL,
  "endTime" time NOT NULL,
  name text NOT NULL,
  email text NOT NULL,
  attendees integer NOT NULL CHECK (attendees > 0),
  purpose text NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
  "reviewedAt" timestamptz,
  "reviewedBy" text,
  CHECK ("endTime" > "startTime")
);
ALTER TABLE bookings DROP CONSTRAINT IF EXISTS bookings_status_check;
ALTER TABLE bookings ADD CONSTRAINT bookings_status_check
  CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled'));
CREATE INDEX IF NOT EXISTS bookings_venue_date_idx ON bookings ("venueId", date);

-- This constraint protects against simultaneous booking requests on separate
-- Vercel instances. Neon supports btree_gist on its standard PostgreSQL plans.
CREATE EXTENSION IF NOT EXISTS btree_gist;
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'bookings_no_overlapping_active'
       AND conrelid = 'bookings'::regclass
  ) THEN
    ALTER TABLE bookings ADD CONSTRAINT bookings_no_overlapping_active
      EXCLUDE USING gist (
        "venueId" WITH =,
        date WITH =,
        tsrange(date + "startTime", date + "endTime", '[)') WITH &&
      ) WHERE (status IN ('pending', 'approved'));
  END IF;
END $$;

-- Sessions are shared across serverless instances, unlike in-memory sessions.
CREATE TABLE IF NOT EXISTS sessions (
  sid text PRIMARY KEY,
  data jsonb NOT NULL,
  expires timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expires_idx ON sessions (expires);

CREATE TABLE IF NOT EXISTS app_settings (
  key text PRIMARY KEY,
  value text NOT NULL
);
